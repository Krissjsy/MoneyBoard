import { test, expect, newAccount, register, logout } from './fixtures'

const api = 'http://localhost:5080/api'
const mailbox = 'http://127.0.0.1:5081'

async function skipSetup(page: import('@playwright/test').Page) {
  await page.getByRole('button', { name: /Skip for now/i }).click()
  await expect(page.getByRole('button', { name: 'Overview' })).toBeVisible()
}

async function currentDate(page: import('@playwright/test').Page) {
  return page.evaluate(() => {
    const now = new Date()
    return `${now.getFullYear()}-${String(now.getMonth() + 1).padStart(2, '0')}-${String(now.getDate()).padStart(2, '0')}`
  })
}

async function addTransaction(page: import('@playwright/test').Page, input: { title: string; amount: string; type: 'income' | 'expense'; category?: string; date: string }) {
  await page.getByRole('button', { name: 'Transactions', exact: true }).click()
  await page.locator('section.data-panel').getByRole('button', { name: 'Add transaction' }).click()
  if (input.type === 'income') await page.getByRole('button', { name: 'Money in' }).click()
  await page.getByLabel(input.type === 'income' ? 'Income source' : 'What was it for?').fill(input.title)
  await page.getByLabel('Amount').fill(input.amount)
  await page.getByLabel('Date').fill(input.date)
  if (input.type === 'expense' && input.category) await page.getByLabel('Category').selectOption({ label: input.category })
  await page.getByRole('button', { name: 'Save transaction' }).click()
  const row = page.locator('.transaction-row').filter({ hasText: input.title })
  await expect(row).toBeVisible()
  return row
}

async function readDashboard(page: import('@playwright/test').Page) {
  const token = await page.evaluate(() => localStorage.getItem('moneyboard.accessToken'))
  const month = await page.evaluate(() => {
    const now = new Date()
    return { year: now.getFullYear(), month: now.getMonth() + 1 }
  })
  const response = await page.request.get(`${api}/dashboard?year=${month.year}&month=${month.month}`, { headers: { Authorization: `Bearer ${token}` } })
  expect(response.ok()).toBeTruthy()
  return response.json()
}

