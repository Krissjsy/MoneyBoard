test('forgot-password email can be captured locally, reset and used to sign in', async ({ monitoredPage: page }) => {
  const account = await register(page, newAccount('recovery'))
  await skipSetup(page)
  await logout(page)
  await fetch(`${mailbox}/messages/clear`, { method: 'POST' })
  await page.getByRole('link', { name: 'Forgot password?' }).click()
  await page.getByLabel('Email').fill(account.email)
  await page.getByRole('button', { name: 'Send reset link' }).click()
  await expect(page.getByRole('status')).toContainText('If an account exists')

  let email = ''
  await expect.poll(async () => {
    const response = await fetch(`${mailbox}/messages/latest`)
    if (!response.ok) return ''
    email = (await response.json()).message
    return email
  }, { timeout: 10_000, message: 'Reset email was not received by the loopback SMTP capture' }).not.toBe('')
  email = email.replace(/=\r?\n/g, '').replace(/=([0-9A-F]{2})/gi, (_, hex: string) => String.fromCharCode(Number.parseInt(hex, 16)))
  const match = email.match(/https?:\/\/[^\s"'<>]+\/reset-password\?[^\s"'<>]+/)
  expect(match, 'captured email should contain a reset URL').toBeTruthy()
  const resetUrl = match![0].replaceAll('&amp;', '&')
  const resetParams = new URL(resetUrl).searchParams
  expect(resetParams.get('email')).toBe(account.email)
  expect(resetParams.get('token')).toBeTruthy()
  await page.goto(resetUrl)
  await expect(page.getByRole('heading', { name: 'Set a new password' })).toBeVisible()
  await page.locator('#new-password').fill('UpdatedSynthetic123!')
  await page.locator('#confirm-password').fill('UpdatedSynthetic123!')
  await page.getByRole('button', { name: 'Reset password' }).click()
  await expect(page.getByRole('status')).toContainText('Your password has been reset')
  await page.getByRole('link', { name: 'Return to sign in' }).first().click()
  await page.getByLabel('Email').fill(account.email)
  await page.getByLabel('Password').fill('UpdatedSynthetic123!')
  await page.getByRole('button', { name: 'Sign in' }).click()
  await expect(page.getByRole('button', { name: 'Overview' })).toBeVisible()
})

test('income, expenses, budgets and dashboard figures stay consistent through CRUD', async ({ monitoredPage: page }) => {
  await register(page, newAccount('transactions'))
  await skipSetup(page)
  const date = await currentDate(page)
  const month = date.slice(0, 7)

  await page.getByRole('button', { name: 'Budgets', exact: true }).click()
  await page.locator('section.data-panel').getByRole('button', { name: 'Add budget' }).click()
  await page.getByLabel('Category').fill('Food')
  await page.getByLabel('Monthly limit').fill('500')
  await page.getByLabel('Month', { exact: true }).fill(month)
  await page.getByRole('button', { name: 'Create budget' }).click()
  const budget = page.locator('.budget-detail').filter({ hasText: 'Food' })
  await expect(budget).toBeVisible()
  await budget.getByRole('button', { name: 'Edit' }).click()
  await page.getByLabel('Monthly limit').fill('600')
  await page.getByRole('button', { name: 'Save changes' }).click()

  const income = await addTransaction(page, { title: 'Synthetic pay', amount: '2500', type: 'income', date })
  await income.getByRole('button', { name: 'Edit' }).click()
  await page.getByLabel('Amount').fill('2600')
  await page.getByRole('button', { name: 'Save changes' }).click()

  const food = await addTransaction(page, { title: 'Market shop', amount: '100', type: 'expense', category: 'Food', date })
  await food.getByRole('button', { name: 'Edit' }).click()
  await page.getByLabel('Amount').fill('125')
  await page.getByRole('button', { name: 'Save changes' }).click()
  const unbudgeted = await addTransaction(page, { title: 'One-off gift', amount: '40', type: 'expense', category: 'Shopping', date })

  await page.getByRole('button', { name: 'Budgets', exact: true }).click()
  await expect(page.locator('.budget-detail').filter({ hasText: 'Food' })).toContainText('£125.00')
  await expect(page.locator('.budget-detail').filter({ hasText: 'Food' })).not.toContainText('Shopping')
  const dashboard = await readDashboard(page)
  expect(dashboard.income).toBe(2600)
  expect(dashboard.expenses).toBe(165)
  expect(dashboard.recent.map((row: { title: string }) => row.title)).toContain('One-off gift')

  await page.getByRole('button', { name: 'Transactions', exact: true }).click()
  page.once('dialog', dialog => dialog.accept())
  await unbudgeted.getByRole('button', { name: 'Delete' }).click()
  const afterDelete = await readDashboard(page)
  expect(afterDelete.expenses).toBe(125)

  const foodAgain = page.locator('.transaction-row').filter({ hasText: 'Market shop' })
  page.once('dialog', dialog => dialog.accept())
  await foodAgain.getByRole('button', { name: 'Delete' }).click()
  const incomeAgain = page.locator('.transaction-row').filter({ hasText: 'Synthetic pay' })
  page.once('dialog', dialog => dialog.accept())
  await incomeAgain.getByRole('button', { name: 'Delete' }).click()
  const finalDashboard = await readDashboard(page)
  expect(finalDashboard.income).toBe(0)
  expect(finalDashboard.expenses).toBe(0)

  await page.getByRole('button', { name: 'Budgets', exact: true }).click()
  const foodBudget = page.locator('.budget-detail').filter({ hasText: 'Food' })
  await expect(foodBudget).toContainText('£0.00')
  page.once('dialog', dialog => dialog.accept())
  await foodBudget.getByRole('button', { name: 'Delete' }).click()
  await expect(page.locator('.budget-detail').filter({ hasText: 'Food' })).toHaveCount(0)
})

