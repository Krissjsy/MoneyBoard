test('financial records persist after refresh and stay isolated between accounts', async ({ monitoredPage: page }) => {
  const firstAccount = await register(page, newAccount('isolation-a'))
  await skipSetup(page)
  const date = await currentDate(page)
  await addTransaction(page, { title: 'Private synthetic income', amount: '777', type: 'income', date })
  await page.reload()
  await page.getByRole('button', { name: 'Transactions', exact: true }).click()
  await expect(page.locator('.transaction-row').filter({ hasText: 'Private synthetic income' })).toBeVisible()
  await logout(page)

  const secondAccount = newAccount('isolation-b')
  await register(page, secondAccount)
  await skipSetup(page)
  await page.getByRole('button', { name: 'Transactions', exact: true }).click()
  await expect(page.locator('.transaction-row').filter({ hasText: 'Private synthetic income' })).toHaveCount(0)
  const secondToken = await page.evaluate(() => localStorage.getItem('moneyboard.accessToken'))
  const secondRowsResponse = await page.request.get(`${api}/transactions`, { headers: { Authorization: `Bearer ${secondToken}` } })
  expect(await secondRowsResponse.json()).toEqual([])

  await logout(page)
  await page.getByLabel('Email').fill(firstAccount.email)
  await page.getByLabel('Password').fill(firstAccount.password)
  await page.getByRole('button', { name: 'Sign in' }).click()
  await page.getByRole('button', { name: 'Transactions', exact: true }).click()
  await expect(page.locator('.transaction-row').filter({ hasText: 'Private synthetic income' })).toBeVisible()
  await logout(page)
  await page.getByLabel('Email').fill(secondAccount.email)
  await page.getByLabel('Password').fill(secondAccount.password)
  await page.getByRole('button', { name: 'Sign in' }).click()
  await page.getByRole('button', { name: 'Transactions', exact: true }).click()
  await expect(page.locator('.transaction-row').filter({ hasText: 'Private synthetic income' })).toHaveCount(0)
})
